"""
flow.py — the store conversation as a Pipecat Flows state machine.

Why: one long system prompt asked the LLM to follow an 8-stage script with
every tool available on every turn, so runs drifted (different greetings,
skipped stages) and the model sometimes said "dikhaata hoon" without calling
try_on_frame. Pipecat Flows (pipecat.flows, in core since pipecat-ai 1.5)
makes each stage a node with only the functions that stage needs
(docs.pipecat.ai/pipecat/flows/flow-configs). Here:

  greet ─record_need─▶ prefs ─set_preferences─▶ show[i] ─next_frame─▶ show[i+1] … ─▶ end_of_list
    │                    ▲                        │  └─like_frame─▶ liked ─wants_executive─▶ lead ─save_contact─▶ lead_done
    ├─browsing / eye test / staff                 └─set_preferences / finish ─▶ goodbye

Everything the customer must hear identically each time (greeting, the
frame announcement, "पसंद आया, या अगला दिखाऊँ?", goodbye) is a fixed
`tts_say` line built here in Python — never generated by the LLM. Showing a
frame on the face is a node pre-action, so it cannot be skipped. The LLM only
classifies answers into function calls and answers free questions.
"""

from typing import Any, Awaitable, Callable

from loguru import logger

from catalogue import resolve_tryon, search_frames
from pipecat.flows import FlowManager, FlowsFunctionSchema, NodeConfig
from speech_text import rupees
from tools import _normalise_args, execute_tool

# ---------------------------------------------------------------------------
# Fixed lines (Devanagari Hindi; brand / product words in English script, as
# Sarvam's TTS best practices recommend).
# ---------------------------------------------------------------------------
GREETING = "नमस्ते जी! Eyenetra में आपका स्वागत है। आज क्या देख रहे हैं — चश्मा, sunglasses, या आँखों की जाँच?"
ASK_PREFS = "बढ़िया! आपका बजट लगभग कितना है, और कोई ख़ास स्टाइल पसंद है — जैसे गोल, चौकोर या aviator?"
BROWSING = "बिल्कुल जी, आराम से देखिए। कुछ पसंद आए तो बताइए, मैं उसे आपके चेहरे पर पहनाकर दिखा दूँगा।"
EYE_TEST = "ज़रूर! हमारे यहाँ आँखों की जाँच हो जाती है, बस पाँच मिनट लगते हैं। मैं अभी स्टाफ़ को बुला रहा हूँ।"
STAFF = "जी, इसमें हमारे स्टाफ़ आपकी मदद करेंगे। मैंने उन्हें बुला दिया है, बस एक मिनट।"
FIRST_FRAME = "यह रहा {brand} का {name}, {price}। स्क्रीन पर अपने चेहरे पर देखिए।"
NEXT_FRAME = "अब यह {brand} का {name}, {price}।"
ASK_NEXT = "पसंद आया, या अगला दिखाऊँ?"
RELAXED = "उस स्टाइल में अभी कुछ नहीं है, पर आपके बजट में ये फ्रेम हैं।"
NO_RESULTS = "इस बजट में अभी कोई फ्रेम नहीं है। बजट थोड़ा बढ़ाएँ, या कोई और स्टाइल देखें?"
END_OF_LIST = "आपकी पसंद के ये सारे फ्रेम थे। कोई और स्टाइल या बजट देखें, या शुरू से दोबारा दिखाऊँ?"
LIKED = "बढ़िया पसंद! {name}, {price}। क्या आप हमारे executive से बात करना चाहेंगे, ताकि lens और बाकी चीज़ें फ़ाइनल हो जाएँ?"
ASK_NAME = "ज़रूर। आपका नाम और मोबाइल नंबर बता दीजिए?"
LEAD_DONE = "धन्यवाद जी! हमारे executive अभी आपसे मिलेंगे।"
GOODBYE = "आने के लिए धन्यवाद! कोई भी फ्रेम दोबारा देखना हो तो बस बोलिए।"

ROLE = """You are the voice assistant of Eyenetra, an optical store in Raipur. You talk to customers out loud through text-to-speech.

Rules:
- Reply in conversational Hindi written in Devanagari script. Write brand names and English product words (frame, lens, sunglasses, aviator) in English letters. Never write Hindi in Roman letters.
- At most two short sentences. No lists, markdown or emojis.
- Never invent prices, discounts, stock, offers, policies, addresses or medical claims. State only facts given in the current task or returned by a function.
- If the customer mentions eye pain, redness, sudden blurred vision, an injury or any medical symptom, call notify_staff and say a staff member is coming. Never diagnose.
- If what you heard is unclear or not addressed to you (other people talking), briefly ask them to repeat. Do not guess.
- Lines like the greeting and "पसंद आया, या अगला दिखाऊँ?" are spoken by the system already; do not repeat them."""

SHAPES = ["round", "rectangular", "square", "aviator", "cat-eye", "oval"]

# Sends one UI event to the try-on page (RTVI server message). Kinds:
#   try_on_frame {sku, name, brand, frameId, variantId, price, shape, index, total}
#   liked {sku}        session_end {}
PushTryOn = Callable[[dict], Awaitable[None]]


def _say(text: str) -> dict:
    return {"type": "tts_say", "text": text}


def _frame_facts(f: dict) -> str:
    return (
        f"{f['brand']} {f['name']}: price {f['price']} rupees, shape {f['shape']}, "
        f"material {f['material']}, for {f['gender']}, {'in stock' if f.get('stock', 0) > 0 else 'out of stock'}."
    )


def find_frames(prefs: dict) -> tuple[list[dict], bool]:
    """Catalogue search for the try-on loop: every in-stock match that has a
    3D model, cheapest first. Relaxes material, then shape, then gender if
    nothing matches; the budget is never relaxed silently.

    Returns (frames, relaxed) — relaxed=True if a stated preference was dropped.
    """
    args = _normalise_args("search_frames", {k: v for k, v in prefs.items() if v not in (None, "")})
    attempts = [args]
    for drop in ("material", "shape", "gender"):
        if args.get(drop):
            attempts.append({k: v for k, v in attempts[-1].items() if k != drop})
    for i, attempt in enumerate(attempts):
        frames = [f for f in search_frames(**attempt, limit=None) if resolve_tryon(f["sku"])]
        if frames:
            return frames, i > 0
    return [], False


class StoreFlow:
    """Builds the nodes; handlers are bound methods (args, flow_manager)."""

    def __init__(self, push_tryon: PushTryOn):
        self._push_tryon = push_tryon

    # -- wiring ------------------------------------------------------------
    def register(self, flow_manager: FlowManager) -> None:
        flow_manager.register_action("show_tryon", self._show_tryon_action)

    def global_functions(self) -> list[FlowsFunctionSchema]:
        return [
            FlowsFunctionSchema(
                name="notify_staff",
                description=(
                    "Call a store staff member. Use for medical eye symptoms, repairs, "
                    "contact lenses, children's eyewear, or when the customer asks for a person."
                ),
                properties={"reason": {"type": "string", "description": "Short reason."}},
                required=["reason"],
                handler=self._notify_staff,
            ),
            FlowsFunctionSchema(
                name="recommend_lens",
                description=(
                    "Lens recommendation from screen time, prescription and age. Call before "
                    "saying anything about which lens suits the customer."
                ),
                properties={
                    "screen_time_hours": {"type": "integer"},
                    "has_power": {"type": "boolean"},
                    "age": {"type": "integer"},
                },
                required=["screen_time_hours", "has_power", "age"],
                handler=self._recommend_lens,
            ),
        ]

    async def _show_tryon_action(self, action: dict, flow_manager: FlowManager) -> None:
        sku = action.get("sku", "")
        result = execute_tool("try_on_frame", {"sku": sku})
        if isinstance(result, dict) and result.get("status") == "shown_on_tryon":
            await self._push_tryon({
                "kind": "try_on_frame",
                "sku": result["sku"],
                "name": result["name"],
                "brand": result["brand"],
                "frameId": result["tryon_frame_id"],
                "variantId": result["tryon_variant_id"],
                **{k: action[k] for k in ("price", "shape", "index", "total") if k in action},
            })
        else:
            logger.warning(f"show_tryon: {sku} could not be shown: {result}")

    async def _notify_staff(self, args: dict, flow_manager: FlowManager):
        return execute_tool("notify_staff", args), None

    async def _recommend_lens(self, args: dict, flow_manager: FlowManager):
        return execute_tool("recommend_lens", args), None

    # -- nodes -------------------------------------------------------------
    def greet_node(self, speak: bool = True) -> NodeConfig:
        return {
            "name": "greet",
            "role_message": ROLE,
            "task_messages": [{
                "role": "developer",
                "content": (
                    "The customer is saying what they came for. Call record_need with the best match: "
                    "eyeglasses (power glasses / frames / chashma), sunglasses, both, eye_test, "
                    "service (repair, adjustment, pickup, contact lenses, kids), or browsing (just looking). "
                    "If unclear, ask one short question."
                ),
            }],
            "pre_actions": [_say(GREETING)] if speak else [],
            "respond_immediately": False,
            "functions": [self._record_need_fn()],
        }

    def _record_need_fn(self) -> FlowsFunctionSchema:
        return FlowsFunctionSchema(
            name="record_need",
            description="Record what the customer is looking for.",
            properties={
                "need": {
                    "type": "string",
                    "enum": ["eyeglasses", "sunglasses", "both", "eye_test", "service", "browsing"],
                },
                "detail": {"type": "string", "description": "Anything else they said (budget, style)."},
            },
            required=["need"],
            handler=self._record_need,
        )

    async def _record_need(self, args: dict, flow_manager: FlowManager):
        need = args.get("need")
        flow_manager.state["need"] = need
        logger.info(f"flow: need={need} detail={args.get('detail')!r}")
        if need in ("eyeglasses", "sunglasses", "both"):
            flow_manager.state["prefs"] = {
                "frame_type": {"eyeglasses": "frame", "sunglasses": "sunglass"}.get(need)
            }
            return None, self.prefs_node()
        if need == "eye_test":
            execute_tool("notify_staff", {"reason": "Customer wants an eye test"})
            return None, self.info_node(EYE_TEST)
        if need == "service":
            execute_tool("notify_staff", {"reason": f"Service request: {args.get('detail') or 'unspecified'}"})
            return None, self.info_node(STAFF)
        return None, self.info_node(BROWSING)

    def info_node(self, line: str) -> NodeConfig:
        """Fixed line, then wait for the customer to engage again."""
        return {
            "name": "info",
            "task_messages": [{
                "role": "developer",
                "content": (
                    "Wait for the customer. When they want to see frames or sunglasses, call record_need. "
                    "Otherwise answer briefly."
                ),
            }],
            "pre_actions": [_say(line)],
            "respond_immediately": False,
            "functions": [self._record_need_fn()],
        }

    def prefs_node(self, line: str = ASK_PREFS) -> NodeConfig:
        return {
            "name": "prefs",
            "task_messages": [{
                "role": "developer",
                "content": (
                    "Collect the customer's budget (maximum price in rupees) and optional style. "
                    f"Shapes: {', '.join(SHAPES)}. As soon as you know the budget, or they say budget "
                    "doesn't matter, call set_preferences with everything known. Ask at most one short "
                    "follow-up question; never ask more than budget and style."
                ),
            }],
            "pre_actions": [_say(line)] if line else [],
            "respond_immediately": False,
            "functions": [self._set_preferences_fn()],
        }

    def _set_preferences_fn(self) -> FlowsFunctionSchema:
        return FlowsFunctionSchema(
            name="set_preferences",
            description="Search the catalogue with the customer's preferences and start showing frames.",
            properties={
                "max_price": {"type": "integer", "description": "Budget in rupees; omit if no limit."},
                "shape": {"type": "string", "enum": SHAPES},
                "material": {"type": "string", "enum": ["acetate", "metal", "titanium", "TR90"]},
                "gender": {"type": "string", "enum": ["male", "female", "unisex"]},
            },
            required=[],
            handler=self._set_preferences,
        )

    async def _set_preferences(self, args: dict, flow_manager: FlowManager):
        prefs = {**flow_manager.state.get("prefs", {}), **{k: v for k, v in args.items() if v not in (None, "")}}
        flow_manager.state["prefs"] = prefs
        frames, relaxed = find_frames(prefs)
        flow_manager.state["frames"] = frames
        flow_manager.state["idx"] = 0
        logger.info(f"flow: prefs={prefs} → {[f['sku'] for f in frames]} relaxed={relaxed}")
        if not frames:
            return {"found": 0}, self.prefs_node(NO_RESULTS)
        return {"found": len(frames)}, self.show_node(frames, 0, intro=RELAXED if relaxed else None)

    def show_node(self, frames: list[dict], idx: int, intro: str | None = None) -> NodeConfig:
        f = frames[idx]
        template = FIRST_FRAME if idx == 0 else NEXT_FRAME
        line = template.format(brand=f["brand"], name=f["name"], price=rupees(f["price"]))
        if intro:
            line = f"{intro} {line}"
        return {
            "name": f"show_{idx}",
            "task_messages": [{
                "role": "developer",
                "content": (
                    f"The customer is seeing this frame on their face: {_frame_facts(f)} "
                    f"It is option {idx + 1} of {len(frames)}. "
                    "If they want another → next_frame. If they like it or want this one → like_frame. "
                    "If they want a different budget or style → set_preferences. If they want to stop → finish. "
                    "If they ask about this frame, answer in one short sentence from the facts above only, "
                    "then ask 'पसंद आया, या अगला दिखाऊँ?'."
                ),
            }],
            "pre_actions": [
                {"type": "show_tryon", "sku": f["sku"], "price": f["price"], "shape": f["shape"],
                 "index": idx, "total": len(frames)},
                _say(f"{line} {ASK_NEXT}"),
            ],
            "respond_immediately": False,
            "functions": [
                self._simple_fn("next_frame", "Show the next matching frame.", self._next_frame),
                self._simple_fn("like_frame", "The customer likes this frame / wants it.", self._like_frame),
                self._set_preferences_fn(),
                self._simple_fn("finish", "The customer wants to stop.", self._finish),
            ],
        }

    def _simple_fn(self, name: str, description: str, handler) -> FlowsFunctionSchema:
        return FlowsFunctionSchema(name=name, description=description, properties={}, required=[], handler=handler)

    async def _next_frame(self, args: dict, flow_manager: FlowManager):
        frames = flow_manager.state.get("frames", [])
        idx = flow_manager.state.get("idx", 0) + 1
        if idx >= len(frames):
            return None, self.end_of_list_node()
        flow_manager.state["idx"] = idx
        return None, self.show_node(frames, idx)

    def end_of_list_node(self) -> NodeConfig:
        return {
            "name": "end_of_list",
            "task_messages": [{
                "role": "developer",
                "content": (
                    "All matching frames were shown. Different budget/style → set_preferences. "
                    "See them again → show_again. Stop → finish."
                ),
            }],
            "pre_actions": [_say(END_OF_LIST)],
            "respond_immediately": False,
            "functions": [
                self._set_preferences_fn(),
                self._simple_fn("show_again", "Show the matching frames again from the first.", self._show_again),
                self._simple_fn("finish", "The customer wants to stop.", self._finish),
            ],
        }

    async def _show_again(self, args: dict, flow_manager: FlowManager):
        frames = flow_manager.state.get("frames", [])
        if not frames:
            return None, self.prefs_node()
        flow_manager.state["idx"] = 0
        return None, self.show_node(frames, 0)

    async def _like_frame(self, args: dict, flow_manager: FlowManager):
        frames = flow_manager.state.get("frames", [])
        f = frames[flow_manager.state.get("idx", 0)]
        flow_manager.state["liked"] = f
        await self._event({"kind": "liked", "sku": f["sku"]})
        return None, {
            "name": "liked",
            "task_messages": [{
                "role": "developer",
                "content": (
                    f"The customer liked {_frame_facts(f)} Yes to meeting an executive → wants_executive. "
                    "Wants to keep looking → next_frame. No / done → finish."
                ),
            }],
            "pre_actions": [_say(LIKED.format(name=f["name"], price=rupees(f["price"])))],
            "respond_immediately": False,
            "functions": [
                self._simple_fn("wants_executive", "Customer agrees to meet an executive.", self._wants_executive),
                self._simple_fn("next_frame", "Show the next matching frame.", self._next_frame),
                self._simple_fn("finish", "The customer is done.", self._finish),
            ],
        }

    async def _wants_executive(self, args: dict, flow_manager: FlowManager):
        return None, {
            "name": "lead",
            "task_messages": [{
                "role": "developer",
                "content": (
                    "Collect the customer's name, then their 10-digit mobile number, one question at a time. "
                    "Then call save_contact. If they don't want to share, call finish."
                ),
            }],
            "pre_actions": [_say(ASK_NAME)],
            "respond_immediately": False,
            "functions": [
                FlowsFunctionSchema(
                    name="save_contact",
                    description="Save the customer's name and mobile number for the executive.",
                    properties={"name": {"type": "string"}, "phone": {"type": "string"}},
                    required=["name", "phone"],
                    handler=self._save_contact,
                ),
                self._simple_fn("finish", "The customer does not want to share details.", self._finish),
            ],
        }

    async def _save_contact(self, args: dict, flow_manager: FlowManager):
        st = flow_manager.state
        liked = st.get("liked") or {}
        prefs = st.get("prefs", {})
        summary = f"Liked {liked.get('brand', '')} {liked.get('name', '')} ({liked.get('sku', '')})".strip()
        result = execute_tool("create_lead", {
            "name": args.get("name", ""),
            "phone": args.get("phone", ""),
            "interest_summary": summary,
            "recommended_frames": [f["sku"] for f in st.get("frames", [])][:5],
            "budget": f"under ₹{prefs['max_price']}" if prefs.get("max_price") else None,
        })
        if isinstance(result, dict) and result.get("error"):
            # Invalid phone etc. — stay in the node and let the LLM ask again.
            return result, None
        execute_tool("notify_staff", {"reason": f"Lead ready: {args.get('name')} — {summary}"})
        await self._event({"kind": "session_end"})
        return result, self.goodbye_node(LEAD_DONE)

    async def _finish(self, args: dict, flow_manager: FlowManager):
        await self._event({"kind": "session_end"})
        return None, self.goodbye_node(GOODBYE)

    async def _event(self, msg: dict) -> None:
        """UI-only event; never let a closed data channel break the flow."""
        if self._push_tryon is None:
            return
        try:
            await self._push_tryon(msg)
        except Exception as e:  # noqa: BLE001
            logger.warning(f"UI event {msg.get('kind')} not delivered: {e}")

    def goodbye_node(self, line: str) -> NodeConfig:
        return {
            "name": "goodbye",
            "task_messages": [{
                "role": "developer",
                "content": "If the customer speaks again and wants frames or sunglasses, call record_need.",
            }],
            "pre_actions": [_say(line)],
            "respond_immediately": False,
            "functions": [self._record_need_fn()],
        }


def state_summary(state: dict[str, Any]) -> str:
    """Compact one-line state for logs."""
    return f"need={state.get('need')} prefs={state.get('prefs')} idx={state.get('idx')} n={len(state.get('frames', []))}"
